"""Emit locate-stage zoomgrid specs (wide windows) for van and white car."""
import json, sys

which = sys.argv[1]
path = sys.argv[2]

# VAN centre trajectory, normalized (hand-seeded, refined each iteration)
VAN = [
    (0.00, 0.828, 0.719), (0.25, 0.838, 0.694), (0.50, 0.847, 0.670),
    (0.75, 0.855, 0.648), (1.00, 0.862, 0.628), (1.25, 0.868, 0.610),
    (1.50, 0.873, 0.594), (1.75, 0.878, 0.579), (2.00, 0.882, 0.565),
    (2.25, 0.886, 0.552), (2.50, 0.890, 0.540), (2.75, 0.893, 0.529),
    (3.00, 0.896, 0.518), (3.25, 0.899, 0.508), (3.50, 0.901, 0.498),
    (3.75, 0.903, 0.489), (4.00, 0.905, 0.480), (4.25, 0.907, 0.471),
    (4.50, 0.909, 0.463), (4.75, 0.911, 0.455), (5.00, 0.912, 0.447),
    (5.25, 0.914, 0.439), (5.50, 0.915, 0.432),
]
CAR = [
    (0.00, 0.691, 0.941), (0.25, 0.712, 0.880), (0.50, 0.733, 0.822),
    (0.75, 0.749, 0.776), (1.00, 0.764, 0.735), (1.25, 0.778, 0.700),
    (1.50, 0.790, 0.669), (1.75, 0.801, 0.642), (2.00, 0.811, 0.618),
    (2.25, 0.819, 0.598), (2.50, 0.827, 0.579), (2.75, 0.834, 0.562),
    (3.00, 0.840, 0.547), (3.25, 0.846, 0.533), (3.50, 0.851, 0.520),
    (3.75, 0.856, 0.508), (4.00, 0.860, 0.497), (4.25, 0.864, 0.487),
    (4.50, 0.868, 0.477), (4.75, 0.871, 0.468), (5.00, 0.874, 0.459),
]

T = VAN if which == "van" else CAR
ITEMS = []
for t, cx, cy in T:
    if which == "van":
        if t <= 2.0:
            hw, hh, st, sc = 0.050, 0.055, 0.01, 5
        else:
            hw, hh, st, sc = 0.032, 0.036, 0.005, 8
    else:
        hw, hh, st, sc = 0.045, 0.050, 0.01, 5
    ITEMS.append({"f": "d%03d" % (int(round(t * 4)) + 1), "cx": cx, "cy": cy,
                  "hw": hw, "hh": hh, "step": st, "scale": sc, "tag": f"t={t:.2f}"})
json.dump({"items": ITEMS}, open(path, "w", encoding="utf-8"), indent=1)
print("wrote", path, len(ITEMS), "items")
