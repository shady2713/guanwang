async (page) => {
  const results = [];
  const errors = [];
  const requests = [];
  const failed = [];
  const assert = (condition, name) => { if (!condition) throw new Error(name); results.push(name); };
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => requests.push({ method: request.method(), url: request.url() }));
  page.on('response', response => { if (response.status() >= 400) failed.push(`${response.status()} ${response.url()}`); });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const base = 'http://127.0.0.1:4173';
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${base}/scenarios/`, { waitUntil: 'networkidle' });
  assert(await page.locator('.scene-card').count() === 6, '默认城市治理展示六个场景');
  assert(await page.locator('#category-city').getAttribute('aria-selected') === 'true', '默认分类已选定');
  assert(await page.locator('#category-tabs [role=tab]').count() === 16, '行业分类完整铺出');
  for (const width of [320, 390, 600, 768, 900, 973, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    const layout = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, width: innerWidth, columns: getComputedStyle(document.querySelector('.scene-grid')).gridTemplateColumns.split(' ').length, buttons: [...document.querySelectorAll('#category-tabs button')].every(x => x.getBoundingClientRect().height >= 44) }));
    assert(layout.scroll <= layout.width, `${width}px 场景页无横向溢出`);
    assert(layout.columns === (width <= 600 ? 1 : width <= 900 ? 2 : 3), `${width}px 场景列数正确`);
    assert(layout.buttons, `${width}px 分类按钮触控高度至少44px`);
  }
  for (const id of await page.locator('#category-tabs button').evaluateAll(nodes => nodes.map(x => x.dataset.category))) {
    await page.locator(`#category-${id}`).click();
    assert(await page.locator('.scene-card').count() === 6 && await page.locator(`#category-${id}`).getAttribute('aria-selected') === 'true' && page.url().split('?')[0].replace(base, '') === '/scenarios/', `${id} 行业同页切换`);
  }
  await page.locator('#category-city').click();
  const firstSix = await page.locator('.scene-card').evaluateAll(nodes => nodes.map(x => x.dataset.item));
  await page.locator('#load-more').click();
  assert(await page.locator('.scene-card').count() === 12, '加载更多追加六个');
  assert(JSON.stringify((await page.locator('.scene-card').evaluateAll(nodes => nodes.map(x => x.dataset.item))).slice(0, 6)) === JSON.stringify(firstSix), '加载后保留原有内容与顺序');
  await page.locator('.scene-card[data-item="216"] .detail-link').click();
  await page.waitForURL('**/detail.html?**');
  assert((await page.locator('.detail-hero p').textContent()).includes('消防登高面'), '车辆详情保留城市应用范围');
  assert(await page.locator('.scope-items h3').count() === 2, '车辆详情仅铺出两个城市细分场景');
  assert(!(await page.locator('.scope-items').textContent()).includes('车牌'), '城市正文未继承跨行业车牌能力');
  assert((await page.locator('main').textContent()).includes('当前目录未提供该场景已验证的完整算法链'), '算法链说明保留规划边界');
  await page.screenshot({ path: 'C:/Users/64576/Desktop/视界/website/checks/scenario-detail-desktop.png', fullPage: true });
  await page.locator('#back-to-catalog').click();
  await page.waitForURL('**/scenarios/?**');
  assert(await page.locator('.scene-card').count() === 12, '返回目录保留已加载数量');
  while (await page.locator('#load-more').isVisible()) await page.locator('#load-more').click();
  assert(await page.locator('.scene-card').count() === 72, '城市72场景全部可到达');
  assert(await page.locator('#all-loaded').isVisible(), '加载完成显示结束状态');
  await page.locator('#view-capability').click();
  assert(await page.locator('#category-tabs [role=tab]').count() === 13, '能力分类替换行业分类');
  for (const id of await page.locator('#category-tabs button').evaluateAll(nodes => nodes.map(x => x.dataset.category))) {
    await page.locator(`#category-${id}`).click();
    assert(await page.locator('.scene-card').count() > 0 && await page.locator(`#category-${id}`).getAttribute('aria-selected') === 'true', `${id} 能力分类可用`);
  }
  await page.locator('#category-people').click();
  await page.locator('#category-people').focus();
  await page.keyboard.press('ArrowRight');
  assert(await page.locator('#category-vehicles').getAttribute('aria-selected') === 'true', '分类支持方向键');
  await page.keyboard.press('End');
  assert(await page.locator('#category-survey_aux').getAttribute('aria-selected') === 'true', '分类End键');
  await page.keyboard.press('Home');
  assert(await page.locator('#category-people').getAttribute('aria-selected') === 'true', '分类Home键');
  await page.locator('#view-industry').click();
  assert(await page.locator('#category-city').getAttribute('aria-selected') === 'true', '两种浏览方式各自记住分类');
  await page.locator('#category-traffic').click();
  await page.goBack();
  assert(await page.locator('#category-city').getAttribute('aria-selected') === 'true', '浏览器后退恢复分类');
  await page.goto(`${base}/scenarios/?view=capability&category=plants&count=12`, { waitUntil: 'networkidle' });
  assert(await page.locator('.scene-card').count() === 12 && await page.locator('#category-plants').getAttribute('aria-selected') === 'true', '分类和加载状态支持直接链接');
  await page.goto(`${base}/scenarios/detail.html?id=910&industry=forest`, { waitUntil: 'networkidle' });
  assert(await page.locator('.scope-items h3').count() === 0 && (await page.locator('main').textContent()).includes('当前行业尚未逐项映射'), '未映射行业不铺出跨行业完整细项');
  await page.goto(`${base}/scenarios/detail.html?id=missing`, { waitUntil: 'networkidle' });
  assert(await page.getByRole('heading', { name: '暂未找到这个场景' }).count() === 1, '无效场景有返回入口');
  await page.goto(`${base}/scenarios/`, { waitUntil: 'networkidle' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.menu-toggle').click();
  assert(await page.locator('#main-nav').isVisible(), '手机导航展开');
  await page.keyboard.press('Escape');
  assert(!(await page.locator('#main-nav').isVisible()) && await page.locator('.menu-toggle').evaluate(x => x === document.activeElement), 'Escape关闭手机导航并恢复焦点');
  await page.locator('.menu-toggle').click();
  await page.locator('#category-title').click();
  assert(!(await page.locator('#main-nav').isVisible()), '点击导航外部可关闭');
  await page.screenshot({ path: 'C:/Users/64576/Desktop/视界/website/checks/scenarios-mobile-390.png', fullPage: true });
  await page.locator('.scene-card').first().locator('.detail-link').click();
  assert(await page.locator('main h1').textContent() === '垃圾杂物识别', '手机场景详情可用');
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '390px详情无横向溢出');
  await page.screenshot({ path: 'C:/Users/64576/Desktop/视界/website/checks/scenario-detail-mobile-390.png', fullPage: true });
  await page.locator('.detail-hero .button').click();
  await page.waitForURL('**/demo/?**');
  assert((await page.locator('#demo-context').textContent()).includes('垃圾杂物识别'), '独立预约页携带场景上下文');
  assert(await page.locator('#demo-form input').count() === 2, '预约仅有公司名称和联系方式');
  await page.getByRole('button', { name: '预约演示', exact: true }).click();
  assert(await page.locator('#company').getAttribute('aria-invalid') === 'true', '预约必填验证');
  await page.locator('#company').fill('测试示例公司');
  await page.locator('#contact').fill('invalid');
  await page.getByRole('button', { name: '预约演示', exact: true }).click();
  assert(await page.locator('#contact').getAttribute('aria-invalid') === 'true', '预约联系方式格式验证');
  await page.locator('#contact').fill('------');
  await page.getByRole('button', { name: '预约演示', exact: true }).click();
  assert(await page.locator('#contact').getAttribute('aria-invalid') === 'true', '纯标点不能作为联系方式');
  await page.locator('#contact').fill('demo@example.com');
  const beforeSubmit = requests.length;
  await page.getByRole('button', { name: '预约演示', exact: true }).click();
  assert((await page.locator('#form-status').textContent()).includes('预约尚未发送'), '演示表单不显示虚假预约成功');
  assert(requests.length === beforeSubmit, '表单不产生提交请求');
  await page.screenshot({ path: 'C:/Users/64576/Desktop/视界/website/checks/demo-mobile-390.png', fullPage: true });
  for (const width of [320, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${width}px预约页无横向溢出`);
    await page.goto(`${base}/scenarios/detail.html?id=216&industry=city`, { waitUntil: 'networkidle' });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${width}px详情无横向溢出`);
    await page.goto(`${base}/demo/`, { waitUntil: 'networkidle' });
  }
  await page.screenshot({ path: 'C:/Users/64576/Desktop/视界/website/checks/demo-desktop-1440.png', fullPage: true });
  await page.goto(`${base}/`, { waitUntil: 'networkidle' });
  await page.getByRole('link', { name: '应用场景', exact: true }).first().click();
  assert(page.url().split('?')[0].replace(base, '') === '/scenarios/', '原首页导航连接新场景页');
  await page.goto(`${base}/`, { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: '预约演示', exact: true }).first().click();
  await page.waitForURL('**/demo/');
  assert(page.url().split('?')[0].replace(base, '') === '/demo/', '原首页预约改为跳页');
  await page.goto(`${base}/scenarios/`, { waitUntil: 'networkidle' });
  await page.screenshot({ path: 'C:/Users/64576/Desktop/视界/website/checks/scenarios-desktop-1440.png', fullPage: true });
  assert(await page.locator('img').evaluateAll(nodes => nodes.every(x => x.complete && x.naturalWidth > 0)), '最终页面图片全部加载');
  assert(errors.length === 0, '无JavaScript运行错误');
  assert(failed.length === 0, '无HTTP资源失败');
  assert(requests.every(x => x.url.startsWith(base + '/')), '网页资源不依赖外部服务');
  return { passed: results.length, results, errors, failed, requestCount: requests.length };
}
