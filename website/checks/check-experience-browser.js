async (page) => {
  const results = [];
  const errors = [];
  const requests = [];
  const failed = [];
  const base = 'http://127.0.0.1:4173';
  const dir = 'C:/Users/64576/Desktop/视界/website/checks/';
  const assert = (condition, name) => { if (!condition) throw new Error(name); results.push(name); };
  const observe = p => {
    p.on('pageerror', error => errors.push(error.message));
    p.on('request', request => requests.push({ method: request.method(), url: request.url() }));
    p.on('response', response => { if (response.status() >= 400) failed.push(`${response.status()} ${response.url()}`); });
  };
  const seek = async (p, ms) => p.locator('#playback-position').evaluate((el, value) => { el.value = String(value); el.dispatchEvent(new Event('input', { bubbles: true })); }, ms);
  const begin = async p => { await p.locator('#begin-experience').click(); await p.waitForTimeout(850); if (await p.locator('#scene-stage').getAttribute('data-playing') === 'true') await p.locator('#play-pause').click(); };
  const loaded = p => p.locator('img').evaluateAll(images => images.every(image => image.complete && image.naturalWidth > 0));
  observe(page);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(`${base}/experience/`, { waitUntil: 'networkidle' });
  assert(await loaded(page), '首页所有摄影素材与图标加载成功');
  const hero = await page.evaluate(() => {
    const drone = document.querySelector('.hero-drone').getBoundingClientRect();
    const title = document.querySelector('#landing-title').getBoundingClientRect();
    return { width: drone.width, overlap: !(drone.right <= title.left || drone.left >= title.right || drone.bottom <= title.top || drone.top >= title.bottom), animation: getComputedStyle(document.querySelector('.hero-drone')).animationName };
  });
  assert(hero.width < 450, '无人机素材尺寸正确');
  assert(!hero.overlap, '无人机不遮挡首屏标题');
  assert(hero.animation === 'none', '减少动画偏好停用无人机悬浮');
  assert(JSON.stringify(await page.locator('.task-tabs strong').allTextContents()) === JSON.stringify(['行业场景', '自然语言', '以图搜图']), '三种任务入口顺序正确');
  await page.screenshot({ path: `${dir}experience-hero-desktop.png` });
  await page.locator('#begin-experience').click();
  await page.waitForTimeout(850);
  assert(await page.locator('.landing-hero').evaluate(el => el.getBoundingClientRect().height === 0), '开始体验收起首屏');
  assert(await page.locator('#experience-title').evaluate(el => el === document.activeElement), '开始体验将焦点移到体验标题');
  await page.locator('#play-pause').click();
  await seek(page, 6000);
  assert(await page.locator('#result-title').textContent() === '区域进入提示', '进入区域后产生示例事件');
  assert(await page.locator('#scene-stage').getAttribute('data-inside') === 'true', '时间轴位置与区域状态一致');
  assert(await page.locator('#show-evidence').isEnabled(), '有事件时可以查看证据');
  assert((await page.locator('#show-evidence').boundingBox()).y + 44 <= 900, '1440×900主操作区证据入口在视口内');
  await page.screenshot({ path: `${dir}experience-active-desktop-900.png` });
  await seek(page, 1000);
  assert(await page.locator('#show-evidence').isDisabled() && await page.locator('#result-title').textContent() === '等待车辆进入', '时间轴回到进入前清除事件');
  await seek(page, 10000);
  assert(await page.locator('#scene-stage').getAttribute('data-inside') === 'false' && await page.locator('#show-evidence').isEnabled(), '离开区域后保留已发生事件');
  await page.locator('#detection-only').click();
  assert(await page.locator('#show-evidence').isDisabled(), '停用判断不产生事件证据');
  assert(await page.locator('.chain-node.bypassed').count() === 2 && await page.locator('#chain-heading').textContent() === '从画面到目标', '目标模式跳过跟踪与条件判断');
  await page.locator('[data-node=output]').click();
  assert(await page.locator('#node-title').textContent() === '目标结果输出' && (await page.locator('#node-description').textContent()).includes('不产生事件证据'), '目标输出详情保持正确能力边界');
  await page.locator('#event-judgement').click();
  assert(await page.locator('#show-evidence').isEnabled() && await page.locator('.chain-node.bypassed').count() === 0, '重新加入判断恢复同一回放位置事件');
  await page.locator('[data-node=input]').click();
  assert(await page.locator('#target-box').evaluate(el => getComputedStyle(el).visibility === 'hidden'), '视频输入节点隐藏分析标记');
  await page.locator('[data-node=detection]').click();
  assert(await page.locator('#target-box').evaluate(el => getComputedStyle(el).visibility === 'visible') && await page.locator('#attention-region').evaluate(el => getComputedStyle(el).visibility === 'hidden'), '车辆检测节点仅展示目标标记');
  await page.locator('[data-node=condition]').click();
  assert(await page.locator('#region-handle').isVisible(), '进入条件节点提供区域操作');
  await seek(page, 6000);
  const clip = await page.locator('#attention-region').evaluate(el => el.style.clipPath);
  const handle = await page.locator('#region-handle').boundingBox();
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2);
  await page.mouse.down();
  await page.mouse.move(handle.x + handle.width / 2 - 280, handle.y + handle.height / 2, { steps: 12 });
  await page.mouse.up();
  assert(await page.locator('#attention-region').evaluate(el => el.style.clipPath) !== clip, '实际鼠标拖动移动关注区域');
  assert(await page.locator('#result-title').textContent() === '当前区域没有进入事件' && await page.locator('#show-evidence').isDisabled(), '区域移出车道后重新计算结果');
  await page.locator('#reset-region').click();
  assert(await page.locator('#show-evidence').isEnabled(), '区域复位恢复当前时刻的事件');
  await page.locator('#region-handle').focus();
  await page.keyboard.press('Shift+ArrowRight');
  assert(await page.locator('#attention-region').evaluate(el => el.style.clipPath) !== clip, '关注区域支持方向键调整');
  await page.keyboard.press('Home');
  assert(await page.locator('#attention-region').evaluate(el => el.style.clipPath) === clip, 'Home键复位关注区域');
  await page.locator('#show-evidence').click();
  assert(await page.locator('#evidence-dialog').evaluate(el => el.open), '事件证据弹窗打开');
  const canvases = await page.locator('.evidence-grid canvas').evaluateAll(nodes => nodes.map(canvas => {
    const data = canvas.getContext('2d').getImageData(0, 0, canvas.width, canvas.height).data;
    let sum = 0; let visible = 0;
    for (let i = 0; i < data.length; i += 4) { sum += data[i] + data[i + 1] + data[i + 2]; if (data[i + 3]) visible++; }
    return { sum, visible };
  }));
  assert(canvases.every(canvas => canvas.visible > 300000) && canvases[0].sum !== canvases[1].sum, '两张证据画面均绘制完成且对应不同时间');
  assert(parseFloat(await page.locator('#before-time').textContent()) < 4.4 && parseFloat(await page.locator('#after-time').textContent()) > 4.4, '进入前后证据时间围绕同一事件');
  await page.screenshot({ path: `${dir}experience-evidence-desktop.png` });
  await page.keyboard.press('Escape');
  assert(!(await page.locator('#evidence-dialog').evaluate(el => el.open)) && await page.locator('#show-evidence').evaluate(el => el === document.activeElement), 'Escape关闭证据并恢复焦点');
  await page.locator('#show-evidence').click();
  await page.locator('#replay-event').click();
  assert(await page.locator('#scene-stage').getAttribute('data-playing') === 'true' && Number(await page.locator('#playback-position').inputValue()) < 4400, '证据回放从进入事件之前开始');
  assert(await page.locator('#play-pause').evaluate(el => el === document.activeElement), '证据回放焦点交给播放控制');
  await page.locator('#play-pause').click();
  await page.locator('#task-language').click();
  assert(await page.locator('#language-controls').isVisible() && !(await page.locator('#industry-controls').isVisible()), '自然语言切换对应输入控件');
  assert(await page.locator('#chain-heading').textContent() === '从画面到目标' && await page.locator('#show-evidence').isDisabled(), '自然语言模式仅展示目标检索');
  await page.locator('[data-node=output]').click();
  assert(await page.locator('#node-title').textContent() === '目标结果输出', '自然语言输出节点无事件输出误标');
  await page.locator('#demo-query').fill('查找红色卡车');
  await page.locator('#language-controls button').click();
  assert(await page.locator('#demo-query').getAttribute('aria-invalid') === 'true' && await page.locator('#scene-stage').getAttribute('data-playing') === 'false', '不支持的语言查询提示预设边界');
  await page.locator('#demo-query').fill(' 查找 白色车辆 ');
  await page.locator('#language-controls button').click();
  assert(await page.locator('#demo-query').getAttribute('aria-invalid') === 'false' && await page.locator('#scene-stage').getAttribute('data-playing') === 'true', '支持的预设查询启动演示');
  await seek(page, 8000);
  assert(await page.locator('#show-evidence').isDisabled(), '自然语言回放不会自动启用事件规则');
  await page.screenshot({ path: `${dir}experience-language-desktop.png` });
  await page.locator('#task-image').click();
  assert(await page.locator('#image-controls').isVisible(), '以图搜图展示参考图与运行入口');
  await page.locator('#run-image-demo').click();
  assert(await page.locator('#scene-stage').getAttribute('data-playing') === 'true' && await page.locator('#show-evidence').isDisabled(), '图片检索启动预设目标演示');
  await seek(page, 6000);
  await page.locator('#task-image').focus();
  await page.keyboard.press('Home');
  assert(await page.locator('#task-industry').getAttribute('aria-selected') === 'true', '任务标签支持Home键');
  await page.keyboard.press('ArrowRight');
  assert(await page.locator('#task-language').getAttribute('aria-selected') === 'true', '任务标签支持方向键');
  await page.keyboard.press('End');
  assert(await page.locator('#task-image').getAttribute('aria-selected') === 'true', '任务标签支持End键');
  await page.locator('#task-industry').click();
  await seek(page, 6000);
  for (const width of [320, 390, 600, 768, 900, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    const layout = await page.evaluate(() => ({
      scroll: document.documentElement.scrollWidth, width: innerWidth,
      controls: [...document.querySelectorAll('.task-tabs button,.chain-node,#region-handle,#play-pause,#reset-playback,#reset-region,#return-intro')].every(el => el.getBoundingClientRect().height >= 44),
      columns: getComputedStyle(document.querySelector('.workbench')).gridTemplateColumns.split(' ').length,
    }));
    assert(layout.scroll <= layout.width, `${width}px体验页无横向溢出`);
    assert(layout.controls, `${width}px核心操作触控高度至少44px`);
    assert(layout.columns === (width <= 900 ? 1 : 2), `${width}px体验布局列数正确`);
  }
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.locator('#return-intro').click();
  assert(await page.locator('#begin-experience').isVisible() && await page.locator('#begin-experience').evaluate(el => el === document.activeElement), '返回首屏恢复开始入口与焦点');
  assert(await page.locator('#scene-stage').getAttribute('data-playing') === 'false', '返回首屏停播演示');
  await page.locator('#playback-position').evaluate(el => { el.value = '6000'; el.dispatchEvent(new Event('input', { bubbles: true })); });
  await page.screenshot({ path: `${dir}experience-default-full.png`, fullPage: true });
  await page.locator('.workbench').screenshot({ path: `${dir}experience-core-desktop.png` });
  await page.locator('.header-demo').click();
  await page.waitForURL(`${base}/demo/`);
  assert(await page.locator('#demo-form input').count() === 2, '预约跳独立页且仅含公司与联系方式');
  await page.goto(`${base}/scenarios/`, { waitUntil: 'networkidle' });
  assert(await page.locator('.scene-card').count() === 6, '已有应用场景页正常连接');

  const mobileContext = await page.context().browser().newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
  const mobile = await mobileContext.newPage(); observe(mobile);
  await mobile.goto(`${base}/experience/`, { waitUntil: 'networkidle' });
  assert(await loaded(mobile), '触控手机素材完整加载');
  await mobile.screenshot({ path: `${dir}experience-hero-touch-phone.png` });
  await mobile.locator('.menu-toggle').tap();
  assert(await mobile.locator('#main-nav').isVisible(), '手机触控展开主导航');
  await mobile.keyboard.press('Escape');
  assert(!(await mobile.locator('#main-nav').isVisible()), '手机导航Escape关闭');
  await begin(mobile); await seek(mobile, 6000);
  const touchHandle = await mobile.locator('#region-handle').boundingBox();
  const session = await mobileContext.newCDPSession(mobile);
  const x = touchHandle.x + touchHandle.width / 2; const y = touchHandle.y + touchHandle.height / 2;
  await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] });
  for (let step = 1; step <= 8; step++) await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x - step * 12, y }] });
  await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  assert(await mobile.locator('#result-title').textContent() === '当前区域没有进入事件', '手机实际触控拖动改变判断结果');
  // Chromium suppresses the click immediately following a synthesized drag.
  await mobile.waitForTimeout(550);
  await mobile.locator('#reset-region').tap();
  await mobile.waitForFunction(() => !document.querySelector('#show-evidence').disabled, null, { timeout: 2000 });
  assert(await mobile.locator('#show-evidence').isEnabled(), '手机触控复位区域恢复结果');
  await mobile.screenshot({ path: `${dir}experience-active-touch-phone.png`, fullPage: true });
  await mobile.locator('#show-evidence').tap();
  await mobile.locator('#evidence-dialog').waitFor({ state: 'visible' });
  assert(await mobile.locator('#evidence-dialog').evaluate(el => el.open), '手机触控打开证据');
  assert(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '手机证据弹窗无横向溢出');
  await mobile.screenshot({ path: `${dir}experience-evidence-touch-phone.png`, fullPage: true });
  await mobile.locator('#close-evidence').tap();
  await mobile.locator('#evidence-dialog').waitFor({ state: 'hidden' });
  assert(!(await mobile.locator('#evidence-dialog').evaluate(el => el.open)), '手机触控关闭证据');
  await mobileContext.close();

  const noJSContext = await page.context().browser().newContext({ viewport: { width: 390, height: 844 }, javaScriptEnabled: false });
  const noJS = await noJSContext.newPage(); observe(noJS);
  await noJS.goto(`${base}/experience/`, { waitUntil: 'networkidle' });
  assert(await noJS.locator('noscript a[href="/scenarios/"]').isVisible() && await noJS.locator('noscript a[href="/demo/"]').isVisible(), '无JavaScript仍有场景与预约的真实入口');
  await noJSContext.close();
  assert(errors.length === 0, '无JavaScript运行错误');
  assert(failed.length === 0, '无HTTP资源失败');
  assert(requests.every(request => request.method === 'GET' && request.url.startsWith(base)), '全程仅本地GET，无在线检索或提交请求');
  await page.goto(`${base}/experience/`, { waitUntil: 'networkidle' });
  return { passed: results.length, results, errors, failed, requests: requests.length };
}
